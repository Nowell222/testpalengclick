
-- Update the payment reference generation function to be non-destructive
-- If a reference number or receipt number is already provided (e.g. from OCR), keep it.

CREATE OR REPLACE FUNCTION public.generate_payment_reference()
RETURNS TRIGGER AS $$
DECLARE
  seq_val BIGINT;
BEGIN
  -- We only need to use the sequence if at least one of the numbers is missing
  IF NEW.reference_number IS NULL OR NEW.receipt_number IS NULL THEN
    seq_val := nextval('payment_ref_seq');
    
    -- If no reference number provided (e.g. walk-in cash payment), generate one
    IF NEW.reference_number IS NULL THEN
      NEW.reference_number := 'PC-' || EXTRACT(YEAR FROM now())::text || '-' || LPAD(seq_val::text, 5, '0');
    END IF;
    
    -- If no receipt number provided, generate one
    -- Note: Receipt numbers are usually always generated by the system as Official Receipts
    IF NEW.receipt_number IS NULL THEN
      NEW.receipt_number := 'RC-' || EXTRACT(YEAR FROM now())::text || '-' || LPAD(seq_val::text, 5, '0');
    END IF;
  END IF;
  
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SET search_path = public;
